# Whether the saved session is still accepted by Instagram. Refreshed on a
# background thread and never on the request path: the launcher polls
# /api/auth/status with a one-second timeout to decide the server has come up,
# so this endpoint must not wait on Instagram.
_session_state: dict = {"ok": None, "checked_at": 0.0, "checking": False, "gen": 0}
_session_state_lock = threading.Lock()
_SESSION_CHECK_TTL = 300


def _refresh_session_state(generation: int) -> None:
    try:
        ok = InstagramWeb(loader_with_session()).verify_session()
    except Exception:
        # Offline, or Instagram was unreadable — report nothing rather than
        # claim the login has died.
        ok = None
    with _session_state_lock:
        if _session_state["gen"] != generation:
            # Someone logged in or out while this probe was in flight, so its
            # verdict is about an account we are no longer using.
            _session_state["checking"] = False
            return
        _session_state.update({"ok": ok, "checked_at": time.time(), "checking": False})


def _session_ok_cached():
    with _session_state_lock:
        stale = time.time() - _session_state["checked_at"] > _SESSION_CHECK_TTL
        if stale and not _session_state["checking"]:
            _session_state["checking"] = True
            generation = _session_state["gen"]
            threading.Thread(target=_refresh_session_state,
                             args=(generation,), daemon=True).start()
        return _session_state["ok"]


def _forget_session_state() -> None:
    with _session_state_lock:
        _session_state.update({"ok": None, "checked_at": 0.0, "checking": False,
                               "gen": _session_state["gen"] + 1})


@app.get("/api/auth/status")
def auth_status():
    state = load_state()
    username = state.get("username")
    if not username:
        return {"logged_in": False}
    if not (SESSIONS_DIR / f"{username}.session").exists():
        return {"logged_in": False}
    # session_ok is True / False / null (not checked yet or could not check).
    return {"logged_in": True, "username": username, "session_ok": _session_ok_cached()}


