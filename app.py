def parse_cookies_blob(blob: str) -> dict:
    blob = blob.strip()
    if not blob:
        raise ValueError("Empty cookies")
    data = json.loads(blob)
    needed = {"sessionid", "ds_user_id", "csrftoken"}
    result: dict[str, str] = {}
    if isinstance(data, list):
        for entry in data:
            if isinstance(entry, dict):
                name = entry.get("name") or entry.get("Name")
                value = entry.get("value") or entry.get("Value")
                if name in needed and value:
                    result[name] = str(value)
    elif isinstance(data, dict):
        for k in needed:
            if k in data and data[k]:
                result[k] = str(data[k])
    missing = needed - result.keys()
    if missing:
        raise ValueError(f"Missing cookies: {', '.join(sorted(missing))}")
    return result


def export_cookies_netscape(session, path: Path) -> None:
    """Write the session cookies in the Netscape format yt-dlp expects.

    instaloader persists a session as a bare {name: value} dict, so cookies
    restored by load_session_from_file come back with no domain and no expiry.
    Taken literally that produced a cookie file with nothing usable in it —
    domain-less cookies were skipped outright, and an expiry of 0 reads as
    "expired in 1970" and is dropped when the file is loaded. Every download
    then ran logged out and Instagram answered "login required". Both fields
    get sensible defaults here instead.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    # A restored session cookie has no expiry attached but is still valid, so
    # give it a horizon comfortably past the end of any run.
    default_expiry = int(time.time()) + 365 * 24 * 3600
    lines = ["# Netscape HTTP Cookie File", "# Generated by Feedscript.", ""]
    written = 0
    for c in session.cookies:
        domain = c.domain or ".instagram.com"
        subdomain = "TRUE" if domain.startswith(".") else "FALSE"
        expires = int(c.expires) if c.expires else default_expiry
        secure = "TRUE" if c.secure else "FALSE"
        lines.append("\t".join([domain, subdomain, c.path or "/", secure, str(expires), c.name, c.value or ""]))
        written += 1
    if not any(c.name == "sessionid" and c.value for c in session.cookies):
        # Writing the file anyway would just produce downloads that fail as
        # "login required" several minutes later.
        raise RuntimeError("The saved session has no Instagram sessionid — log out and log in again.")
    path.write_text("\n".join(lines) + "\n")
    # The file holds a live session cookie; keep it out of other users' reach.
    try:
        path.chmod(0o600)
    except OSError:
        pass


def ytdlp_download(post_url: str, dest: Path, cookies_file: Path) -> Path:
    import yt_dlp
    dest.parent.mkdir(parents=True, exist_ok=True)
    base = dest.with_suffix("")
    opts = {
        "outtmpl": str(base) + ".%(ext)s",
        "format": "bestvideo[ext=mp4]+bestaudio[ext=m4a]/best[ext=mp4]/bestvideo+bestaudio/best",
        "merge_output_format": "mp4",
        "postprocessors": [{"key": "FFmpegVideoConvertor", "preferedformat": "mp4"}],
        "quiet": True,
        "no_warnings": True,
        "cookiefile": str(cookies_file),
        "noprogress": True,
        "overwrites": True,
        "retries": 3,
        "fragment_retries": 3,
    }
    with yt_dlp.YoutubeDL(opts) as ydl:
        ydl.download([post_url])
    for p in sorted(base.parent.glob(base.name + ".*")):
        if p.suffix.lower() in (".mp4", ".mkv", ".webm", ".mov", ".m4v"):
            if p != dest:
                p.rename(dest)
            return dest
    raise FileNotFoundError(f"No video could be downloaded for {post_url}")


def has_audio(path: Path) -> bool:
    try:
        r = subprocess.run(
            ["ffprobe", "-v", "error", "-select_streams", "a",
             "-show_entries", "stream=codec_type",
             "-of", "default=nw=1:nk=1", str(path)],
            capture_output=True, text=True, timeout=20,
        )
        return "audio" in r.stdout.strip()
    except Exception:
        return True


