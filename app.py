def run_transcribe_job(job_id: str, req: TranscribeRequest):
    job = _jobs[job_id]
    final_file: Optional[Path] = None
    temp_dir: Optional[Path] = None
    cookies_dir: Optional[Path] = None
    try:
        L = loader_with_session()
        target = req.target.strip().lstrip("@")
        ts = time.strftime("%Y-%m-%d_%H-%M-%S")
        run_name = safe_name(req.run_name) if req.run_name else ts

        if req.output_dir:
            base_out = Path(req.output_dir).expanduser()
            if not base_out.is_absolute():
                base_out = (ROOT / base_out).resolve()
            else:
                base_out = base_out.resolve()
        else:
            base_out = OUTPUT_DIR
        base_out.mkdir(parents=True, exist_ok=True)
        out_dir = base_out / safe_name(target)
        out_dir.mkdir(parents=True, exist_ok=True)
        _sweep_stale_tmp(out_dir)
        final_file = _reserve_final_file(out_dir, run_name)
        run_name = final_file.stem
        # uuid suffix: two jobs started in the same second must not share a
        # temp dir, or their downloads overwrite each other.
        temp_dir = out_dir / f"_tmp_{run_name}_{uuid.uuid4().hex[:6]}"
        temp_dir.mkdir(exist_ok=True)
        job["out_dir"] = str(out_dir)
        job["final_file"] = str(final_file)

        api = InstagramWeb(L)

        def ensure_cookies() -> Path:
            """The cookie file yt-dlp needs, created on first use.

            It holds a live Instagram session, so it is written only if the
            fallback is actually reached, and into the app's own data
            directory rather than the chosen output folder — that is routinely
            a synced Dropbox or Desktop path. The direct CDN path is
            pre-signed and is deliberately sent no cookies at all.
            """
            nonlocal cookies_dir
            if cookies_dir is None:
                cookies_dir = DATA_DIR / f"_cookies_{job_id}"
                cookies_dir.mkdir(parents=True, exist_ok=True)
                try:
                    cookies_dir.chmod(0o700)
                except OSError:
                    pass
                export_cookies_netscape(L.context._session, cookies_dir / "cookies.txt")
            return cookies_dir / "cookies.txt"

        total = len(req.posts)
        emit(job, {"type": "job_start", "total": total, "target": target, "final_file": str(final_file)})
        emit(job, {"type": "phase_start", "phase": "download", "total": total})
        emit(job, {"type": "phase_start", "phase": "transcribe", "total": total})

        work_queue: Queue = Queue(maxsize=3)
        results: list[dict] = []
        results_lock = threading.Lock()

        def downloader():
            try:
                if not job.get("cancelled"):
                    # One walk of the feed resolves every URL this run still
                    # needs; doing it per post would restart at page 1 each
                    # time and grow quadratically with the selection.
                    prefetch_video_urls(api, target, [p.shortcode for p in req.posts],
                                        should_stop=lambda: bool(job.get("cancelled")))
                for idx, p in enumerate(req.posts):
                    if job.get("cancelled"):
                        break
                    sc = p.shortcode
                    # The shortcode arrives in the request body, so it must not
                    # be trusted to be a safe path component.
                    vp = temp_dir / f"{safe_name(sc)}.mp4"
                    url = f"https://www.instagram.com/p/{sc}/"
                    emit(job, {"type": "item_start", "phase": "download", "index": idx, "total": total, "shortcode": sc})
                    try:
                        try:
                            # Preferred path: Instagram's own CDN URL. It is a
                            # progressive MP4 with audio already muxed in, so
                            # it needs neither an extractor nor an ffmpeg merge.
                            fetch_video(api, target, sc, vp)
                        except (IGError, OSError) as e:
                            # yt-dlp remains the safety net for anything the
                            # API path could not resolve.
                            emit(job, {"type": "log", "message": f"Direct download of {sc} failed ({e}); trying yt-dlp."})
                            ytdlp_download(url, vp, ensure_cookies())
                        emit(job, {"type": "item_done", "phase": "download", "index": idx, "total": total, "shortcode": sc, "bytes": vp.stat().st_size})
                        work_queue.put((idx, p, vp))
                    except Exception as e:
                        emit(job, {"type": "item_error", "phase": "download", "shortcode": sc, "error": str(e) or type(e).__name__})
                    if idx < total - 1 and not job.get("cancelled"):
                        human_sleep(2.0, 5.0)
            finally:
                work_queue.put(None)

        def transcriber():
            whisper_mod = None
            while True:
                item = work_queue.get()
                if item is None:
                    break
                if job.get("cancelled"):
                    try:
                        item[2].unlink(missing_ok=True)
                    except Exception:
                        pass
                    continue
                idx, p, vp = item
                sc = p.shortcode
                emit(job, {"type": "item_start", "phase": "transcribe", "index": idx, "total": total, "shortcode": sc})
                try:
                    if not has_audio(vp):
                        meta = build_meta(p, "", None, req.model, note="no audio track")
                        emit(job, {"type": "item_skip", "phase": "transcribe", "shortcode": sc, "reason": "no audio track"})
                    else:
                        if whisper_mod is None:
                            emit(job, {"type": "log", "message": "Loading transcription model…"})
                            whisper_mod = get_whisper(req.model)
                            emit(job, {"type": "log", "message": "Transcription model ready"})
                        result = whisper_mod.transcribe(str(vp), fp16=False)
                        meta = build_meta(p, result["text"].strip(), result.get("language"), req.model)
                        emit(job, {"type": "item_done", "phase": "transcribe", "index": idx, "total": total, "shortcode": sc})
                    with results_lock:
                        results.append(meta)
                except Exception as e:
                    emit(job, {"type": "item_error", "phase": "transcribe", "shortcode": sc, "error": str(e) or type(e).__name__})
                finally:
                    vp.unlink(missing_ok=True)

        dl_thread = threading.Thread(target=downloader, daemon=True)
        tx_thread = threading.Thread(target=transcriber, daemon=True)
        dl_thread.start()
        tx_thread.start()
        dl_thread.join()
        tx_thread.join()

        summary = {
            "target": target,
            "run_name": run_name,
            "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
            "whisper_model": req.model,
            "count": len(results),
            "videos": sorted(results, key=lambda r: r.get("shortcode", "")),
        }
        final_file.write_text(json.dumps(summary, indent=2, ensure_ascii=False))

        if job.get("cancelled"):
            emit(job, {"type": "job_cancelled", "final_file": str(final_file)})
        else:
            emit(job, {"type": "job_done", "final_file": str(final_file)})
        job["done"] = True
    except Exception as e:
        emit(job, {"type": "job_error", "error": str(e) or type(e).__name__})
        job["done"] = True
    finally:
        # Always, even on a crash: the temp dir can hold a cookies.txt with a
        # live Instagram session in the user's own output folder.
        if temp_dir is not None:
            _cleanup_temp(temp_dir)
        if cookies_dir is not None:
            shutil.rmtree(cookies_dir, ignore_errors=True)
        if final_file is not None:
            with _finals_lock:
                _active_finals.discard(final_file)


def _cleanup_temp(temp_dir: Path) -> None:
    try:
        for leftover in temp_dir.iterdir():
            leftover.unlink(missing_ok=True)
        temp_dir.rmdir()
    except OSError:
        pass


@app.post("/api/transcribe")
def transcribe_start(req: TranscribeRequest):
    if not req.posts:
        raise HTTPException(400, "No posts selected")
    # Duplicate shortcodes (e.g. a pinned reel selected twice) would download
    # to the same paths concurrently and corrupt each other.
    seen: set = set()
    unique_posts = []
    for p in req.posts:
        if p.shortcode not in seen:
            seen.add(p.shortcode)
            unique_posts.append(p)
    req.posts = unique_posts
    job_id = uuid.uuid4().hex
    _jobs[job_id] = {"events": [], "done": False, "cancelled": False}
    executor.submit(run_transcribe_job, job_id, req)
    return {"job_id": job_id}


@app.get("/api/transcribe/{job_id}/events")
async def transcribe_events(job_id: str, request: Request):
    if job_id not in _jobs:
        raise HTTPException(404, "Unknown job")

    async def gen():
        sent = 0
        while True:
            if await request.is_disconnected():
                return
            job = _jobs[job_id]
            while sent < len(job["events"]):
                yield sse_event(job["events"][sent])
                sent += 1
            if job.get("done") and sent >= len(job["events"]):
                return
            await asyncio.sleep(0.3)

    return StreamingResponse(gen(), media_type="text/event-stream")


