@app.get("/api/posts/{target}")
async def stream_posts(
    target: str,
    request: Request,
    limit: int = 200,
    date_from: Optional[str] = None,
    date_to: Optional[str] = None,
):
    target = target.strip().lstrip("@")
    events: Queue = Queue()
    stop = threading.Event()

    def produce():
        try:
            df = parse_date(date_from)
            dto = parse_date(date_to)
        except ValueError:
            events.put({"error": "Invalid date filter"})
            return
        try:
            L = loader_with_session()
        except HTTPException as e:
            events.put({"error": e.detail})
            return
        if stop.is_set():
            return

        api = InstagramWeb(L)
        try:
            prof = api.profile(target)
        except IGNotFound:
            events.put({"error": "Profile not found"})
            return
        except IGError as e:
            events.put({"error": str(e) or "Instagram request failed."})
            return
        except Exception as e:
            events.put({"error": str(e) or type(e).__name__ or "Instagram request failed."})
            return

        events.put({
            "type": "profile",
            "username": prof["username"],
            "full_name": prof["full_name"],
            "posts_count": prof["posts_count"],
            "followers": prof["followers"],
            "is_private": prof["is_private"],
        })

        if prof["is_private"] and not prof["followed_by_viewer"]:
            events.put({"error": "Profile is private and not followed"})
            return

        user_id = prof["id"]
        count = 0
        scanned = 0

        def end_early(message: str) -> None:
            """Close out a scan that stopped before it meant to.

            Anything already streamed is only usable once `done` arrives — that
            is what sorts the table and pre-checks the top rows — so a failure
            partway through reports the reason and still finishes, rather than
            leaving the user with rows they cannot act on.
            """
            if count:
                events.put({"type": "status", "message": message})
                events.put({"type": "done", "count": count, "scanned": scanned})
            else:
                events.put({"error": message})

        seen: set = set()
        max_id: Optional[str] = None
        pages = 0

        try:
            while True:
                if stop.is_set():
                    return
                page = api.user_feed(user_id, max_id)
                pages += 1
                items = page.get("items") or []
                if not items:
                    break

                finished = False
                for item in items:
                    if stop.is_set():
                        return
                    code = item.get("code")
                    if not code or code in seen:
                        # Pinned posts are served at the top of the feed and
                        # then again in date order.
                        continue
                    seen.add(code)
                    scanned += 1

                    taken_at = _api_taken_at(item)
                    pinned = any(str(u) == user_id
                                 for u in (item.get("timeline_pinned_user_ids") or []))
                    if df and taken_at and taken_at < df:
                        # A pinned post can be years old and still lead the
                        # feed, so it must not end a date-filtered scan.
                        if pinned:
                            continue
                        finished = True
                        break
                    if not _api_is_video(item):
                        continue
                    if dto and taken_at and taken_at > dto:
                        continue

                    remember_video_url(code, _api_video_url(item))
                    count += 1
                    events.put({"type": "post", "post": serialize_api_post(item)})
                    if count >= limit:
                        finished = True
                        break

                if finished:
                    break
                max_id = page.get("next_max_id")
                if not page.get("more_available") or not max_id:
                    break
                if pages >= IG_MAX_PAGES:
                    # Say so rather than letting a truncated scan read as
                    # "that is everything this account has".
                    events.put({"type": "status",
                                "message": f"Stopped after scanning {scanned} posts — narrow the date range to reach older ones."})
                    break
                if pages % 10 == 0:
                    events.put({"type": "status",
                                "message": f"Scanned {scanned} posts, {count} videos so far…"})
                human_sleep(0.8, 1.8)
        except IGRateLimited as e:
            end_early(str(e) or "Instagram is rate-limiting this account.")
            return
        except IGError as e:
            end_early(str(e) or "Instagram request failed.")
            return
        except Exception as e:
            end_early("Stopped: " + (str(e) or type(e).__name__))
            return

        events.put({"type": "done", "count": count, "scanned": scanned})

    def produce_safely():
        # All instaloader work happens on this worker thread: its blocking
        # requests must never run on the event loop, or every other request
        # (and the whole UI) freezes until Instagram answers.
        try:
            produce()
        except Exception as e:
            events.put({"error": str(e) or type(e).__name__})
        finally:
            events.put(None)

    async def gen():
        threading.Thread(target=produce_safely, daemon=True).start()
        try:
            while True:
                if await request.is_disconnected():
                    return
                try:
                    item = events.get_nowait()
                except Empty:
                    await asyncio.sleep(0.15)
                    continue
                if item is None:
                    return
                yield sse_event(item)
        finally:
            # Tell the worker to stop scanning — an abandoned stream must not
            # keep spending Instagram's rate budget.
            stop.set()

    return StreamingResponse(gen(), media_type="text/event-stream")


def sse_event(data: dict) -> str:
    return f"data: {json.dumps(data)}\n\n"


